# Builds native/src/gl_overlay_font.h: two alpha atlases (title bold, body) for the GL overlays.
import sys
from PIL import Image, ImageDraw, ImageFont
fonts=[("title","/usr/share/fonts/dejavu-sans-fonts/DejaVuSans-Bold.ttf"),("body",sys.argv[1])]
PX=48; out=["/* generated by jojo/tools/mkfont.py: ASCII 32..126 alpha atlases */"]
for name,path in fonts:
    f=ImageFont.truetype(path,PX); asc,desc=f.getmetrics(); ch=asc+desc+2
    cw=max(int(f.getlength(chr(c)))+4 for c in range(32,127))
    cols=16; rows=6; W=cols*cw; H=rows*ch
    im=Image.new("L",(W,H),0); d=ImageDraw.Draw(im)
    adv=[]
    for i,c in enumerate(range(32,127)):
        x=(i%cols)*cw; y=(i//cols)*ch; d.text((x+2,y+1),chr(c),font=f,fill=255); adv.append(f.getlength(chr(c)))
    # solid block in the last cell for rectangles
    i=95; x=(i%cols)*cw; y=(i//cols)*ch; d.rectangle([x+2,y+2,x+cw-3,y+ch-3],fill=255)
    out.append(f"static const int font_{name}_w={W},font_{name}_h={H},font_{name}_cw={cw},font_{name}_ch={ch},font_{name}_asc={asc};")
    out.append(f"static const float font_{name}_adv[95]={{"+",".join(f"{a:.2f}f" for a in adv)+"};")
    b=im.tobytes(); out.append(f"static const unsigned char font_{name}_px[{len(b)}]={{")
    for k in range(0,len(b),40): out.append(",".join(str(v) for v in b[k:k+40])+",")
    out.append("};")
open(sys.argv[2],"w").write("\n".join(out)+"\n")
