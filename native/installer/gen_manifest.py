"""Generate disc metadata from a known-good NHL Hitz 2003 USA extraction; no game bytes are embedded."""
import argparse
import hashlib
import json
from pathlib import Path
import struct


def generate(source, output):
    source = Path(source).resolve()
    xbe = (source / 'default.xbe').read_bytes()
    if xbe[:4] != b'XBEH' or len(xbe) < 0x11c:
        raise ValueError('default.xbe is not an Xbox executable')
    base, = struct.unpack_from('<I', xbe, 0x104)
    certificate, = struct.unpack_from('<I', xbe, 0x118)
    offset = certificate-base
    if offset < 0 or offset+12 > len(xbe) or struct.unpack_from('<I', xbe, offset+8)[0] != 0x4D57000B:
        raise ValueError('Expected NHL Hitz 2003 USA, title ID 0x4D57000B')
    skip = {'default_analysis.json', '.hitz-import-complete'}
    files = sorted((p.relative_to(source).as_posix(), p.stat().st_size)
                   for p in source.rglob('*') if p.is_file() and p.name not in skip)
    for name, size in files:
        if any(part in ('', '.', '..') for part in name.split('/')) or not name.isascii() or '\n' in name or '\r' in name:
            raise ValueError(f'Unsafe disc path: {name!r}')
    digest = hashlib.sha256(xbe).digest()
    signature = 'HITZ03_IMPORT_V1:' + hashlib.sha256(
        digest + json.dumps(files, separators=(',', ':')).encode()).hexdigest()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    lines = ['/* Disc metadata generated by gen_manifest.py; contains no game data. */',
             'static const unsigned char XBE_SHA256[32] = {' + ','.join(map(str, digest)) + '};',
             f'#define IMPORT_SIGNATURE "{signature}"',
             'static const struct { const char *path; unsigned long long size; } MANIFEST[] = {']
    lines += [f'    {{ {json.dumps(name)}, {size}ULL }},' for name, size in files]
    total = sum(size for _, size in files)
    lines += ['};', f'#define MANIFEST_COUNT {len(files)}', f'#define MANIFEST_BYTES {total}ULL', '']
    (output / 'manifest.h').write_text('\n'.join(lines), encoding='utf-8')
    (output / 'disc_manifest.iss').write_text(
        f'; Generated metadata; no game data.\n#define GameDataBytes {total}\n'
        f'#define ImportSignature "{signature}"\n', encoding='utf-8')
    print(f'{len(files)} files, {total:,} bytes; XBE SHA-256 {digest.hex()}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    generate(args.source, args.output)
